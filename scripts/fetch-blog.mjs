// Downloads the Hashnode RSS feed and writes it to src/data/blog-posts.ts.
// Hashnode's GraphQL API needs a paid plan, but the RSS feed is free. The browser cannot read the
// feed directly (no CORS headers), so it is fetched here, at build time, and bundled with the site.
//
// Run: node scripts/fetch-blog.mjs   (runs automatically before `npm run build`)
// If the download fails, the previous src/data/blog-posts.ts is kept and the build continues.
import { writeFileSync, existsSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const HOST = "ahmadkanaan.hashnode.dev"
const FEED_URL = `https://${HOST}/rss.xml`
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "blog-posts.ts")
const MAX_POSTS = 10
const WORDS_PER_MINUTE = 200

const decode = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&amp;/g, "&")

// Text of the first <tag>…</tag>, with the CDATA wrapper removed when present
function text(block, tag) {
  const m = block.match(new RegExp(`<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`))
  if (!m) return ""
  const cdata = m[1].match(/^\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*$/)
  return (cdata ? cdata[1] : decode(m[1])).trim()
}

function parseItems(xml) {
  return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map(([, block]) => {
    const html = text(block, "content:encoded")
    const words = html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length
    const url = text(block, "link")
    const cover = block.match(/<enclosure[^>]*\surl="([^"]+)"/)
    const tags = [...block.matchAll(/<category>([\s\S]*?)<\/category>/g)].map(([, c]) => {
      const cdata = c.match(/^\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*$/)
      return { name: (cdata ? cdata[1] : decode(c)).trim() }
    })
    const published = new Date(text(block, "pubDate"))
    return {
      id: text(block, "guid") || url,
      title: text(block, "title"),
      brief: text(block, "description"),
      publishedAt: Number.isNaN(published.getTime()) ? new Date(0).toISOString() : published.toISOString(),
      readTimeInMinutes: Math.max(1, Math.round(words / WORDS_PER_MINUTE)),
      ...(cover ? { coverImage: { url: decode(cover[1]) } } : {}),
      tags,
      url,
    }
  })
}

async function main() {
  const res = await fetch(FEED_URL, { headers: { "User-Agent": "portfolio-build" } })
  if (!res.ok) throw new Error(`HTTP ${res.status} from ${FEED_URL}`)
  const posts = parseItems(await res.text())
    .filter((p) => p.title && p.url)
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
    .slice(0, MAX_POSTS)
  if (posts.length === 0) throw new Error("feed contained no posts")

  const file = `// Generated by scripts/fetch-blog.mjs from ${FEED_URL}. Do not edit by hand.
import type { PostNode } from "@/lib/hashnode"

export const blogPosts: PostNode[] = ${JSON.stringify(posts, null, 2)}
`
  writeFileSync(OUT, file)
  console.log(`fetch-blog: wrote ${posts.length} post(s) to src/data/blog-posts.ts`)
}

main().catch((err) => {
  if (existsSync(OUT)) {
    console.warn(`fetch-blog: ${err.message}; keeping the existing src/data/blog-posts.ts`)
  } else {
    console.error(`fetch-blog: ${err.message}, and there is no existing src/data/blog-posts.ts`)
    process.exitCode = 1
  }
})
